import { GoBoard } from '@kaya/goboard'
import type { Sign, SignMap, Vertex } from '@kaya/goboard'
import { GameTree } from '@kaya/gametree'
import type { GameTreeNode, Primitive } from '@kaya/gametree'

export { GameTree }
export type { GameTreeNode }

// Augment GameTree with a currentId property for navigation state
declare module '@kaya/gametree' {
  interface GameTree<T = Record<string, Primitive[]>> {
    currentId?: string | number
  }
}

function vertexToSgf([x, y]: Vertex): string {
  return (
    String.fromCharCode('a'.charCodeAt(0) + x) +
    String.fromCharCode('a'.charCodeAt(0) + y)
  )
}

function sgfToVertex(sgf: string): Vertex {
  return [
    sgf.charCodeAt(0) - 'a'.charCodeAt(0),
    sgf.charCodeAt(1) - 'a'.charCodeAt(0),
  ]
}

/**
 * Child-index path from the root to the current navigation node.
 * Used to persist the cursor across an SGF round trip, where node ids
 * are regenerated by the parser and cannot be reused directly.
 */
export function getCursorPath(tree: GameTree): number[] {
  const path: number[] = []
  let node: GameTreeNode | null = tree.get(tree.currentId ?? tree.root.id)
  while (node != null && node.parentId != null) {
    // Capture for the callback below — node is reassigned at the loop end.
    const current = node
    const parent: GameTreeNode | null = tree.get(current.parentId)
    if (parent == null) break
    const index = parent.children.findIndex((child) => child.id === current.id)
    path.unshift(index >= 0 ? index : 0)
    node = parent
  }
  return path
}

/**
 * Move the current navigation cursor along a child-index path from the
 * root (the inverse of getCursorPath). Invalid or out-of-range indices
 * stop the walk early — a broken path degrades to the deepest valid node
 * instead of failing the whole restore.
 */
export function setCursorPath(tree: GameTree, path: readonly number[]): void {
  let node: GameTreeNode = tree.root
  for (const index of path) {
    if (!Number.isInteger(index) || index < 0) break
    const child: GameTreeNode | undefined = node.children[index]
    if (child == null) break
    node = child
  }
  tree.currentId = node.id
}

export function createGameTree(_size: number): GameTree {
  const tree = new GameTree({
    root: {
      id: 'root',
      data: {},
      parentId: null,
      children: [],
    },
  })
  tree.currentId = tree.root.id
  return tree
}

/**
 * Path of nodes from the root to the given node (inclusive), root first.
 * Returns null when the node does not exist in the tree.
 *
 * Note: node resolution deliberately does NOT use tree.get(id) for ids that
 * may have been stringified — GameTree.get compares ids strictly (`===`),
 * so a string lookup of a numeric id fails AND poisons the node cache with
 * a null entry. Structural search with String() comparison is safe for both.
 */
export function getPathNodes(
  tree: GameTree,
  nodeId: string | number,
): GameTreeNode[] | null {
  const node = findNodeById(tree, nodeId)
  if (node == null) return null
  const ancestors = [...tree.listNodesVertically(node.id, -1, {})]
  ancestors.reverse()
  return ancestors
}

/**
 * Move the navigation cursor to an arbitrary node (tree-view navigation).
 * Like undo/redo, returns a NEW tree (the input is never mutated) so React
 * state updates and the autosave effect observe an identity change.
 * Returns null when the node does not exist.
 */
export function navigateToNode(
  tree: GameTree,
  nodeId: string | number,
): GameTree | null {
  const node = findNodeById(tree, nodeId)
  if (node == null) return null
  const newTree = cloneTree(tree)
  newTree.currentId = node.id
  return newTree
}

/** Depth-first search by stringified id — type-safe alternative to tree.get. */
export function findNodeById(
  tree: GameTree,
  nodeId: string | number,
): GameTreeNode | null {
  const target = String(nodeId)
  const visit = (node: GameTreeNode): GameTreeNode | null => {
    if (String(node.id) === target) return node
    for (const child of node.children) {
      const found = visit(child)
      if (found != null) return found
    }
    return null
  }
  return visit(tree.root)
}

/**
 * SGF properties that affect position or turn. Two move nodes may only be
 * treated as the same variation when their board-relevant data matches
 * exactly; setup stones (AB/AW/AE), player-to-play (PL), or a second move
 * prop keep nodes as separate siblings.
 */
const BOARD_PROPS: ReadonlySet<string> = new Set(['B', 'W', 'AB', 'AW', 'AE', 'PL'])

/** A pass value: an empty property list (B[]) or a single empty value (B['']). */
function isPassValue(values: Primitive[] | undefined): boolean {
  if (values == null) return false
  return values.length === 0 || (values.length === 1 && values[0] === '')
}

/**
 * True when `data` has no board-changing property other than `prop`.
 * Comments/annotations (C, GB, UC, …) are not board props — they never
 * block reuse because the reused node (with them) is kept as is.
 */
function hasNoOtherBoardProps(
  data: Record<string, Primitive[]>,
  prop: string,
): boolean {
  return !Object.keys(data).some((key) => key !== prop && BOARD_PROPS.has(key))
}

/**
 * Find an existing child of `parentId` that represents exactly the same
 * board action as the move/pass about to be appended, so replaying a line
 * reuses it instead of creating a duplicate sibling variation.
 */
function findReusableChild(
  tree: GameTree,
  parentId: string | number,
  prop: 'B' | 'W',
  matches: (data: Record<string, Primitive[]>, prop: 'B' | 'W') => boolean,
): GameTreeNode | null {
  const parentNode = tree.get(parentId)
  return (
    parentNode?.children.find((child) => matches(child.data, prop)) ?? null
  )
}

/**
 * Append a move node under the current node and move the cursor onto it.
 * When the current node already has a child representing the EXACT same
 * move — same color, same SGF coordinate, no extra board-changing
 * properties — that child is reused instead of creating a duplicate
 * sibling variation: its whole subtree and annotations are preserved and
 * the cursor is set to it. Genuinely different moves (other coordinate,
 * other color, setup properties) still append a separate sibling.
 *
 * Returns a NEW tree (the input is never mutated) so React state updates
 * and the autosave effect observe an identity change even on reuse.
 */
export function appendMove(
  tree: GameTree,
  vertex: Vertex,
  sign: number,
): GameTree {
  const currentId = tree.currentId ?? tree.root.id
  const prop = sign === 1 ? 'B' : 'W'
  const coord = vertexToSgf(vertex)

  const reused = findReusableChild(tree, currentId, prop, (data, p) => {
    const values = data[p]
    return (
      values != null &&
      values.length === 1 &&
      values[0] === coord &&
      hasNoOtherBoardProps(data, p)
    )
  })
  if (reused != null) {
    const newTree = cloneTree(tree)
    newTree.currentId = reused.id
    return newTree
  }

  const newTree = tree.mutate((draft) => {
    draft.appendNode(currentId, { [prop]: [coord] })
  })

  const currentNode = newTree.get(currentId)
  const newNode = currentNode?.children[currentNode.children.length - 1]
  newTree.currentId = newNode?.id ?? currentId

  return newTree
}

/**
 * Append a pass node under the current node and move the cursor onto it.
 * Like appendMove, an existing child that is the same color's pass (with
 * no extra board-changing properties) is reused — cursor set onto it,
 * subtree/annotations preserved — instead of creating a duplicate sibling.
 */
export function appendPass(tree: GameTree, sign: number): GameTree {
  const currentId = tree.currentId ?? tree.root.id
  const prop = sign === 1 ? 'B' : 'W'

  const reused = findReusableChild(tree, currentId, prop, (data, p) => {
    return isPassValue(data[p]) && hasNoOtherBoardProps(data, p)
  })
  if (reused != null) {
    const newTree = cloneTree(tree)
    newTree.currentId = reused.id
    return newTree
  }

  const newTree = tree.mutate((draft) => {
    draft.appendNode(currentId, { [prop]: [] })
  })

  const currentNode = newTree.get(currentId)
  const newNode = currentNode?.children[currentNode.children.length - 1]
  newTree.currentId = newNode?.id ?? currentId

  return newTree
}

function cloneTree(tree: GameTree): GameTree {
  const clone = new GameTree({
    getId: tree.getId,
    merger: tree.merger,
    root: JSON.parse(JSON.stringify(tree.root)) as GameTreeNode,
  })
  return clone
}

export function undo(tree: GameTree): GameTree | null {
  const currentId = tree.currentId ?? tree.root.id
  const prevNode = tree.navigate(currentId, -1, {})
  if (prevNode == null || prevNode.id === currentId) {
    return null
  }

  const newTree = cloneTree(tree)
  newTree.currentId = prevNode.id
  return newTree
}

export function redo(tree: GameTree): GameTree | null {
  const currentId = tree.currentId ?? tree.root.id
  const nextNode = tree.navigate(currentId, 1, {})
  if (nextNode == null || nextNode.id === currentId) {
    return null
  }

  const newTree = cloneTree(tree)
  newTree.currentId = nextNode.id
  return newTree
}

/** Setup 배치 (AB/AW 좌표 하나): 가드 없는 착점 + 실패 시 원판 반환. */
function applySetup(board: GoBoard, sign: Sign, coord: string, size: number): GoBoard {
  if (typeof coord !== 'string' || coord.length < 2) return board
  const vertex = sgfToVertex(coord)
  if (vertex[0] < 0 || vertex[0] >= size || vertex[1] < 0 || vertex[1] >= size) {
    return board
  }
  try {
    return board.makeMove(sign, vertex, {
      preventOverwrite: true,
      preventSuicide: false,
      preventKo: false,
    })
  } catch {
    return board
  }
}

export interface SetupStone {
  vertex: Vertex
  sign: number
}

/**
 * 현재 경로의 setup 돌(AB/AW) — root 부터 순서대로.
 * 엔진(GTP) 재생용: 착수 목록과 별도로 setup 돌을 먼저 play 해야
 * 스크린샷 이어하기 국면이 엔진에 전달된다.
 */
export function getSetupStones(tree: GameTree): SetupStone[] {
  const currentId = tree.currentId ?? tree.root.id
  const nodes = [...tree.listNodesVertically(currentId, -1, {})].reverse()

  const stones: SetupStone[] = []
  for (const node of nodes) {
    const data = node.data as { AB?: string[]; AW?: string[] }
    for (const coord of data.AB ?? []) {
      if (typeof coord === 'string' && coord.length >= 2) {
        stones.push({ vertex: sgfToVertex(coord), sign: 1 })
      }
    }
    for (const coord of data.AW ?? []) {
      if (typeof coord === 'string' && coord.length >= 2) {
        stones.push({ vertex: sgfToVertex(coord), sign: -1 })
      }
    }
  }
  return stones
}

export function getCurrentSignMap(tree: GameTree, size: number): SignMap {
  const currentId = tree.currentId ?? tree.root.id
  let board = GoBoard.fromDimensions(size, size)

  const nodes = [...tree.listNodesVertically(currentId, -1, {})].reverse()

  for (const node of nodes) {
    const data = node.data as { B?: string[]; W?: string[]; AB?: string[]; AW?: string[] }

    // Setup properties (AB/AW) — 모든 값을 적용한다 (root 포함).
    // 스크린샷 인식 등 임의 국면이 setup 으로 들어온다. 부분 재생 중 캡처는
    // 일어나지 않는다: 최종 국면의 부분집합 재생에서는 어떤 그룹의 활기도
    // 최종 국면 기준 하한 이하로 내려가지 않기 때문.
    for (const coord of data.AB ?? []) {
      board = applySetup(board, 1, coord, size)
    }
    for (const coord of data.AW ?? []) {
      board = applySetup(board, -1, coord, size)
    }

    if (node.id === tree.root.id) continue

    const sign =
      data.B != null && data.B.length > 0 && data.B[0] !== ''
        ? 1
        : data.W != null && data.W.length > 0 && data.W[0] !== ''
          ? -1
          : 0

    if (sign === 0) {
      // Pass — no board change, but we still need to track the turn
      continue
    }

    const prop = sign === 1 ? data.B : data.W
    if (prop == null || prop.length === 0 || prop[0] === '') {
      // Pass — no board change
      continue
    }

    const coord = prop[0]
    if (typeof coord === 'string' && coord.length >= 2) {
      const vertex = sgfToVertex(coord)
      try {
        board = board.makeMove(sign, vertex, {
          preventOverwrite: true,
          preventSuicide: false,
          preventKo: false,
        })
      } catch {
        // Illegal move in history — skip
      }
    }
  }

  return board.signMap
}

export function getMoveList(
  tree: GameTree,
): { vertex: Vertex | 'pass'; sign: number }[] {
  const currentId = tree.currentId ?? tree.root.id
  const nodes = [...tree.listNodesVertically(currentId, -1, {})].reverse()

  const moves: { vertex: Vertex | 'pass'; sign: number }[] = []

  for (const node of nodes) {
    if (node.id === tree.root.id) continue

    const data = node.data as { B?: string[]; W?: string[] }
    if (data.B != null) {
      const prop = data.B
      if (prop.length === 0 || prop[0] === '') {
        moves.push({ vertex: 'pass', sign: 1 })
      } else {
        moves.push({ vertex: sgfToVertex(prop[0] as string), sign: 1 })
      }
    } else if (data.W != null) {
      const prop = data.W
      if (prop.length === 0 || prop[0] === '') {
        moves.push({ vertex: 'pass', sign: -1 })
      } else {
        moves.push({ vertex: sgfToVertex(prop[0] as string), sign: -1 })
      }
    }
  }

  return moves
}

/**
 * Move-number options for getMoveNumberMap.
 */
export interface MoveNumberOptions {
  /**
   * "번호 표시" numbering: move nodes AFTER this node are numbered 1, 2, …
   * (the anchor's own stone — everything already on the board when the
   * button was pressed — stays unlabeled). The anchor must lie on the
   * current path (root → cursor) — when the cursor leaves the anchor's
   * subtree (off-path/sibling branch) NO labels are produced at all, so
   * another branch can never be mislabeled from a stale anchor.
   */
  fromNodeId?: string | number | null
}

/**
 * Move-number labels for the stones visible on the CURRENT branch (the
 * path root → cursor). Review/놓아보기 numbering rules:
 *   - every move node (B/W, including passes) advances the move counter,
 *   - passes and setup stones (AB/AW) get NO label,
 *   - a stone that has been captured is off the board → no label,
 *   - a re-placed vertex shows the number of the move that last placed it.
 * The result mirrors getCurrentSignMap's replay semantics exactly (illegal
 * history moves are skipped), so a label always sits on a stone the board
 * actually shows.
 *
 * Without options the whole path is numbered ("전체 수순" mode). With
 * `fromNodeId` ("번호 표시" mode) the counter starts at the node AFTER the
 * anchor — stones already on the board stay unlabeled — and when the anchor
 * is not on the current path the function returns null ("no labels").
 */
export function getMoveNumberMap(
  tree: GameTree,
  size: number,
  options?: MoveNumberOptions,
): (number | null)[][] | null {
  const fromNodeId = options?.fromNodeId ?? null
  const currentId = tree.currentId ?? tree.root.id
  const nodes = [...tree.listNodesVertically(currentId, -1, {})].reverse()

  const numbers: (number | null)[][] = Array.from({ length: size }, () =>
    Array<number | null>(size).fill(null),
  )
  let board = GoBoard.fromDimensions(size, size)
  let moveNumber = 0

  // Anchor mode: numbering starts at the node AFTER the anchor along the
  // path — the anchor itself and everything before it are still replayed
  // (board state) but produce no labels or counter, so stones already on
  // the board at press time stay unlabeled.
  let anchorIndex = -1
  if (fromNodeId != null) {
    const target = String(fromNodeId)
    anchorIndex = nodes.findIndex((node) => String(node.id) === target)
    if (anchorIndex === -1) return null // anchor off the current path
  }

  for (let i = 0; i < nodes.length; i++) {
    const node = nodes[i]!
    const numbering = fromNodeId == null || i > anchorIndex
    const data = node.data as { B?: string[]; W?: string[]; AB?: string[]; AW?: string[] }

    for (const coord of data.AB ?? []) {
      board = applySetup(board, 1, coord, size)
    }
    for (const coord of data.AW ?? []) {
      board = applySetup(board, -1, coord, size)
    }

    if (node.id === tree.root.id) continue

    // Move node? (B or W property present — including empty = pass.)
    if (data.B === undefined && data.W === undefined) continue

    if (numbering) moveNumber += 1

    const isBlackMove = data.B !== undefined
    const prop = isBlackMove ? data.B : data.W
    if (prop == null || prop.length === 0 || prop[0] === '') {
      continue // pass — counts, but carries no label
    }

    const sign = isBlackMove ? 1 : -1
    const coord = prop[0]
    if (typeof coord === 'string' && coord.length >= 2) {
      const vertex = sgfToVertex(coord)
      try {
        board = board.makeMove(sign, vertex, {
          preventOverwrite: true,
          preventSuicide: false,
          preventKo: false,
        })
        if (
          numbering &&
          vertex[0] >= 0 &&
          vertex[0] < size &&
          vertex[1] >= 0 &&
          vertex[1] < size
        ) {
          numbers[vertex[1]]![vertex[0]] = moveNumber
        }
      } catch {
        // Illegal move in history — skip (same as getCurrentSignMap).
      }
    }
  }

  // Only stones still on the board carry a label; captured points clear.
  const signMap = board.signMap
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      if (signMap[y]?.[x] === 0) {
        numbers[y]![x] = null
      }
    }
  }
  return numbers
}
